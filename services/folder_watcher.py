import os
import re
import csv
import time
import hashlib
import threading
import shutil
from datetime import datetime
from typing import List, Dict, Callable, Optional, Set

from utils.file_utils import sanitize_folder_name, sanitize_filename, get_unique_filepath, ALLOWED_EXTENSIONS
from services.notification_service import send_windows_toast, send_telegram_alert

EXTENSIONS = ALLOWED_EXTENSIONS + ('.rtf',)
MANIFEST_HEADERS = [
    "Downloaded At", "Company", "Applicant Name", "Applicant Email",
    "Email Subject", "Filename", "File Size (KB)", "File Path",
    "SHA256", "Status", "Notes"
]

def parse_cloud_filename(filename: str):
    """
    Parses filenames generated by Google Apps Script or standard filenames:
    Format: YYYYMMDD_HHmm_ApplicantName_OriginalFilename.ext
    e.g. 20261017_1030_John Doe_Resume.pdf
    """
    match = re.match(r"^(\d{8}_\d{4})_([^_]+)_(.+)$", filename)
    if match:
        timestamp_str = match.group(1)
        applicant_name = match.group(2).strip()
        orig_filename = match.group(3).strip()
        return applicant_name, orig_filename, timestamp_str
    
    # Fallback: clean base name
    base_name = os.path.splitext(filename)[0]
    clean_name = re.sub(r'[\r\n\t_]', ' ', base_name).strip()
    return clean_name if clean_name else "Candidate", filename, ""

def compute_file_sha256(filepath: str) -> str:
    hasher = hashlib.sha256()
    with open(filepath, 'rb') as f:
        while chunk := f.read(65536):
            hasher.update(chunk)
    return hasher.hexdigest()

class FolderWatcher:
    """
    Monitors the local Google Drive Synced folder for new resumes.
    Automatically indexes new files into resumes_manifest.csv, sends notifications,
    and updates the candidate pipeline without requiring direct Gmail IMAP connection.
    """
    def __init__(
        self,
        watch_dir: str,
        companies: Optional[List[Dict[str, str]]] = None,
        create_subfolders: bool = True,
        enable_desktop_toasts: bool = True,
        telegram_token: str = "",
        telegram_chat_id: str = "",
        log_callback: Optional[Callable[[str, str], None]] = None,
        poll_interval: int = 5
    ):
        self.watch_dir = os.path.abspath(watch_dir.strip())
        self.companies = companies or []
        self.create_subfolders = create_subfolders
        self.enable_desktop_toasts = enable_desktop_toasts
        self.telegram_token = telegram_token.strip()
        self.telegram_chat_id = telegram_chat_id.strip()
        self.log = log_callback or (lambda m, l: None)
        self.poll_interval = max(3, poll_interval)
        self.stop_event = threading.Event()
        self.scan_now_event = threading.Event()
        self.thread: Optional[threading.Thread] = None
        self.known_hashes: Set[str] = set()
        self.known_files: Set[str] = set()
        self.duplicates_prevented = 0
        self._load_existing_manifest()

    def _load_existing_manifest(self):
        manifest_file = os.path.join(self.watch_dir, "resumes_manifest.csv")
        if os.path.exists(manifest_file):
            try:
                with open(manifest_file, "r", encoding="utf-8") as f:
                    reader = csv.DictReader(f)
                    for row in reader:
                        sha = row.get("SHA256", "").strip()
                        if sha:
                            self.known_hashes.add(sha)
                        fpath = row.get("File Path", "").strip()
                        if fpath:
                            self.known_files.add(os.path.normcase(os.path.abspath(fpath)))
            except Exception as e:
                self.log(f"Notice: Could not index existing manifest records: {e}", "WARNING")

    def start(self):
        self.stop_event.clear()
        self.scan_now_event.clear()
        self.thread = threading.Thread(target=self._run_loop, daemon=True)
        self.thread.start()

    def stop(self):
        self.stop_event.set()
        self.scan_now_event.set()
        if self.thread and self.thread.is_alive():
            self.thread.join(timeout=2.0)

    def trigger_scan_now(self):
        self.scan_now_event.set()

    def _match_company(self, filename: str, applicant_name: str) -> str:
        search_target = f"{filename} {applicant_name}".lower()
        for comp in self.companies:
            kw = (comp.get("keyword") or "").strip().lower()
            if kw and kw in search_target:
                return comp.get("name") or "General"
        return "General"

    def _record_manifest(
        self,
        company: str,
        app_name: str,
        fname: str,
        size_kb: float,
        full_path: str,
        sha256_hash: str
    ):
        try:
            os.makedirs(self.watch_dir, exist_ok=True)
            manifest_file = os.path.join(self.watch_dir, "resumes_manifest.csv")
            needs_header = not os.path.exists(manifest_file)

            with open(manifest_file, "a", newline="", encoding="utf-8") as f:
                writer = csv.writer(f)
                if needs_header:
                    writer.writerow(MANIFEST_HEADERS)
                writer.writerow([
                    datetime.now().strftime("%Y-%m-%d %H:%M:%S"),
                    company,
                    app_name,
                    "Cloud-Synced",
                    "Google Drive Auto-Sync",
                    fname,
                    size_kb,
                    full_path,
                    sha256_hash,
                    "New",
                    "Auto-synced from Google Drive"
                ])
        except Exception as e:
            self.log(f"Error updating manifest: {e}", "ERROR")

    def scan_directory(self):
        if not os.path.exists(self.watch_dir):
            return

        try:
            entries = os.scandir(self.watch_dir)
        except Exception as e:
            self.log(f"Cannot read directory '{self.watch_dir}': {e}", "WARNING")
            return

        for entry in entries:
            if not entry.is_file():
                continue

            fname = entry.name
            ext = os.path.splitext(fname)[1].lower()
            if ext not in EXTENSIONS:
                continue

            # Skip manifest itself or temp files
            if fname.lower() in ("resumes_manifest.csv", "resumes_manifest_summary.csv") or fname.startswith("~$"):
                continue

            full_path = os.path.abspath(entry.path)
            norm_path = os.path.normcase(full_path)

            try:
                # Ensure file is done writing (Google Drive sync might still be streaming)
                file_size = os.path.getsize(full_path)
                if file_size == 0:
                    continue

                sha256_val = compute_file_sha256(full_path)
                if sha256_val in self.known_hashes:
                    self.duplicates_prevented += 1
                    continue

                applicant_name, orig_name, _ = parse_cloud_filename(fname)
                company = self._match_company(fname, applicant_name)
                size_kb = round(file_size / 1024.0, 2)

                # Move into title/company subfolder if enabled
                if self.create_subfolders and company:
                    target_folder = os.path.join(self.watch_dir, sanitize_folder_name(company))
                    if os.path.abspath(target_folder) != os.path.abspath(self.watch_dir):
                        os.makedirs(target_folder, exist_ok=True)
                        dest_path = get_unique_filepath(target_folder, fname)
                        try:
                            shutil.move(full_path, dest_path)
                            full_path = dest_path
                            norm_path = os.path.normcase(full_path)
                        except Exception as move_err:
                            self.log(f"Notice: Could not move '{fname}' to subfolder '{company}': {move_err}", "WARNING")

                self._record_manifest(company, applicant_name, fname, size_kb, full_path, sha256_val)
                self.known_hashes.add(sha256_val)
                self.known_files.add(norm_path)

                self.log(f"[CLOUD SYNC] 📄 New resume indexed: '{fname}' ({size_kb} KB) for {company}", "SUCCESS")

                # Native Windows Toast Notification
                if self.enable_desktop_toasts:
                    send_windows_toast(
                        title=f"📄 New Resume ({company})",
                        message=f"Candidate: {applicant_name}\nFile: {fname}",
                        sound=True
                    )

                # Optional Telegram Notification
                if self.telegram_token and self.telegram_chat_id:
                    tg_msg = (
                        f"🚀 <b>New Resume Synced</b>\n\n"
                        f"👤 <b>Candidate:</b> {applicant_name}\n"
                        f"🏢 <b>Company:</b> {company}\n"
                        f"📁 <b>Filename:</b> <code>{fname}</code>\n"
                        f"📦 <b>Size:</b> {size_kb} KB\n"
                        f"⏰ <b>Time:</b> {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}"
                    )
                    send_telegram_alert(self.telegram_token, self.telegram_chat_id, tg_msg)

            except Exception as e:
                # File might be locked temporarily by Google Drive desktop sync
                continue

    def _run_loop(self):
        self.log(f"☁️ Cloud Sync Folder Watcher started. Monitoring: '{self.watch_dir}'", "INFO")
        while not self.stop_event.is_set():
            try:
                self.scan_directory()
            except Exception as e:
                self.log(f"Folder watcher loop error: {e}", "WARNING")

            self.scan_now_event.wait(timeout=self.poll_interval)
            self.scan_now_event.clear()

        self.log("Cloud Sync Folder Watcher stopped.", "INFO")
